Versão 1.0

AXION ENGENHARIA
CNPJ 07.749.348/0001-25

1. OBJETO E FINALIDADE

O presente Termo estabelece as condições de ciência e utilização dos recursos corporativos da AXION ENGENHARIA relacionados ao AXION Acompanhamento de Contratos (ACC), incluindo contas corporativas, sistemas, documentos, comunicações e informações utilizadas na gestão dos contratos e projetos da empresa.

2. ESCOPO

O ACC poderá processar informações corporativas relacionadas às atividades profissionais do usuário, incluindo documentos contratuais, aditivos, Change Orders, pedidos de compra, aprovações por e-mail, atas, relatórios, cronogramas, documentos técnicos, comerciais, financeiros, administrativos, jurídicos, de ESG e SSMA e demais registros necessários à gestão dos projetos.

3. E-MAIL CORPORATIVO

Mensagens e anexos enviados ou recebidos por meio das contas corporativas da AXION poderão ser consultados e processados pelo ACC quando relacionados às atividades profissionais, projetos, contratos, clientes, fornecedores e demais finalidades empresariais legítimas.

O processamento deverá observar critérios de finalidade, adequação, necessidade, segurança e minimização, não tendo por finalidade a vigilância da vida privada do colaborador nem a análise indiscriminada de comunicações sem relação com as atividades corporativas.

4. DADOS DE TERCEIROS

Informações de clientes, fornecedores, colaboradores e terceiros poderão ser processadas quando necessárias à execução de atividades empresariais, contratuais, administrativas, jurídicas, de compliance, ESG, SSMA, auditoria ou proteção dos direitos da AXION.

5. FINALIDADES DO ACC

O ACC poderá utilizar as informações para identificar e acompanhar obrigações, responsabilidades, prazos, eventos, riscos contratuais, alterações de escopo, Change Orders, aprovações, evidências, comunicações relevantes, alertas, ações, auditorias e demais elementos relacionados à gestão dos contratos e projetos.

6. AUTOMAÇÃO E INTELIGÊNCIA ARTIFICIAL

O ACC poderá utilizar recursos automatizados e de inteligência artificial para classificação, correlação, extração, organização e análise de informações, identificação de cláusulas, eventos e riscos e elaboração de resumos, alertas e recomendações.

Resultados produzidos por inteligência artificial têm natureza assistiva e não constituem, isoladamente, decisão vinculante. Decisões relevantes deverão permanecer sujeitas à análise e responsabilidade humana.

7. BASES LEGAIS

O tratamento de dados pessoais será realizado de acordo com a legislação aplicável e conforme a finalidade específica de cada operação, podendo fundamentar-se, entre outras hipóteses legalmente aplicáveis, no cumprimento de obrigação legal ou regulatória, execução de contrato, exercício regular de direitos, legítimo interesse ou consentimento quando efetivamente necessário.

A ciência deste Termo não significa que todas as operações de tratamento realizadas pela AXION estejam fundamentadas em consentimento.

8. DADOS PESSOAIS SENSÍVEIS

O ACC não tem como finalidade a coleta indiscriminada de dados pessoais sensíveis. Caso tais dados sejam necessários em situação específica, seu tratamento deverá possuir finalidade legítima, necessidade comprovada, base legal adequada e controles de acesso compatíveis.

9. COMPARTILHAMENTO E OPERADORES

Para funcionamento do ACC, determinadas informações poderão ser processadas por fornecedores de infraestrutura, armazenamento, autenticação, comunicação, inteligência artificial e outros serviços tecnológicos contratados pela AXION, exclusivamente dentro das finalidades autorizadas e das medidas de segurança aplicáveis.

10. SEGURANÇA E CONTROLE

O ACC poderá utilizar autenticação, controle de perfis e permissões, registros de auditoria, rastreabilidade, versionamento, segregação de acesso e demais mecanismos destinados à proteção das informações corporativas.

11. DEVERES DO USUÁRIO

O usuário deverá utilizar os recursos corporativos de forma profissional, preservar a confidencialidade das informações, não compartilhar credenciais, não divulgar ou copiar informações sem autorização e comunicar incidentes ou suspeitas de segurança conforme as políticas internas da AXION.

12. DIREITOS DOS TITULARES

Os direitos relativos a dados pessoais poderão ser exercidos conforme a legislação aplicável e os procedimentos de privacidade adotados pela AXION.

13. RETENÇÃO E ELIMINAÇÃO

As informações poderão ser mantidas pelo período necessário ao cumprimento das respectivas finalidades empresariais, contratuais, legais, regulatórias, de auditoria e de exercício regular de direitos.

O desligamento ou a retirada de acesso de um usuário não implica eliminação automática de documentos, comunicações e evidências pertencentes aos registros corporativos da AXION.

14. RECURSOS CORPORATIVOS

Contas, sistemas, equipamentos e demais recursos fornecidos pela AXION destinam-se prioritariamente às atividades profissionais e poderão gerar registros operacionais, de segurança, auditoria e rastreabilidade necessários à administração e proteção dos ambientes corporativos.

15. POLÍTICA DE PRIVACIDADE

Este Termo deve ser interpretado em conjunto com a Política de Privacidade e demais políticas internas aplicáveis da AXION.

16. CONDIÇÕES DE USO DO ACC

O ACC é uma ferramenta corporativa destinada exclusivamente a usuários autorizados. Informações e análises produzidas pelo sistema deverão ser utilizadas dentro das atribuições profissionais de cada usuário.

O usuário reconhece que recursos automatizados e de inteligência artificial podem apresentar limitações ou erros e que recomendações do sistema não substituem avaliações profissionais quando estas forem necessárias.

17. REGISTROS E AUDITORIA

A utilização do ACC poderá gerar registros de acesso, operação, aprovação, alteração e demais eventos relevantes destinados à segurança, rastreabilidade, auditoria e preservação de evidências.

18. ALTERAÇÕES E NOVAS VERSÕES

Alterações materiais deste Termo poderão resultar na publicação de nova versão e na solicitação de nova ciência aos usuários.

A aprovação de uma nova versão não elimina ou modifica os registros históricos de versões anteriormente apresentadas e aprovadas.

